$results = @()
$counts = [ordered]@{
    Present = 0; ValueAbsent = 0; KeyMissing = 0; KeyPresent = 0; Error = 0; NotProbed = 0
}
$settingIndex = 0
$total = $settings.Count

foreach ($setting in $settings) {
    $settingIndex++
    if (($settingIndex % 40) -eq 0) {
        Write-Progress -Activity 'Probing catalog targets' -Status ('{0} / {1}' -f $settingIndex, $total) `
            -PercentComplete ([int](100 * $settingIndex / $total))
    }

    $targetResults = @()
    foreach ($target in @($setting.targets)) {
        $tr = [ordered]@{
            key            = [string]$target.key
            joinKey        = [string]$target.joinKey
            kind           = [string]$target.kind
            status         = 'NotProbed'
            effectiveValue = $null
            effectivePath  = $null
            valueKind      = $null
            paths          = @()
            note           = $null
        }

        if ($target.kind -ne 'Registry') {
            # powercfg is skipped deliberately: unhiding a hidden powercfg setting requires a
            # registry WRITE, which would stop this being a clean-install reading. Scheduled tasks
            # are read below, separately from the registry pass.
            $tr.note = 'Not probed in v1 (see script header).'
            $counts.NotProbed++
            $targetResults += $tr
            continue
        }

        $enumerate = ([bool]$target.perNetworkInterface) -or ([bool]$target.perMonitor)
        $ordered = Get-HklmFirstOrder (@($target.paths) | ForEach-Object { [string]$_ })

        $pathResults = @()
        foreach ($p in $ordered) {
            $pathResults += (Read-OnePath -Path $p -ValueName ([string]$target.valueName) `
                -KeyExistenceOnly ([bool]$target.keyExistenceOnly) -EnumerateSubKeys $enumerate)
        }
        $tr.paths = $pathResults

        # Fold to the effective reading the detection engine would see.
        $winner = $null
        foreach ($pr in $pathResults) {
            if ($pr.status -eq 'Present' -or $pr.status -eq 'KeyPresent') { $winner = $pr; break }
        }
        if ($null -ne $winner) {
            $tr.status = $winner.status
            $tr.effectiveValue = $winner.value
            $tr.effectivePath = $winner.path
            $tr.valueKind = $winner.valueKind
        } elseif ($pathResults.Count -eq 0) {
            # A registry target declaring no paths is a catalog defect, not a missing key. Must not
            # fold to KeyMissing, where it would be indistinguishable from a real absent reading.
            $tr.status = 'Error'
            $tr.note = 'Target declares no registry paths.'
        } elseif (@($pathResults | Where-Object { $_.status -eq 'ValueAbsent' }).Count -gt 0) {
            $tr.status = 'ValueAbsent'
        } elseif (@($pathResults | Where-Object { $_.status -eq 'Error' }).Count -eq $pathResults.Count) {
            $tr.status = 'Error'
        } else {
            $tr.status = 'KeyMissing'
        }

        # Targets needing a reduction (REG_BINARY byte/bitmask, packed composite string) are
        # recorded RAW. The reduction is replayed later against Winhance.Core's RegTargetReader
        # rather than re-implemented here, where it could silently diverge.
        if (($null -ne $target.byteIndex) -or ([bool]$target.byteOnly) -or
            ($null -ne $target.bitMask) -or (-not [string]::IsNullOrEmpty([string]$target.compositeStringKey))) {
            $tr.note = 'Raw value recorded; catalog reduction (byte/bitmask/composite) not applied here.'
        }

        if ($counts.Contains($tr.status)) { $counts[$tr.status]++ }
        $targetResults += $tr
    }

    $results += [ordered]@{
        id      = [string]$setting.id
        targets = $targetResults
    }
}
Write-Progress -Activity 'Probing catalog targets' -Completed

