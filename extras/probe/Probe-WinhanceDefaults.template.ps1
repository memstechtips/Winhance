# =============================================================================================
# JSON output writer
#
# Hand-rolled rather than ConvertTo-Json on purpose:
#   - ConvertTo-Json in PS 5.1 defaults to -Depth 2 and SILENTLY flattens anything deeper into
#     "System.Object[]" strings, which would quietly destroy most of this output.
#   - PS 5.1's serializer has a maxJsonLength ceiling that this output could approach.
#   - We want byte[] as hex and every non-ASCII character escaped, so the result file is ASCII.
# =============================================================================================

function ConvertTo-JsonStringLiteral {
    param([string] $Text)
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append('"')
    foreach ($ch in $Text.ToCharArray()) {
        $code = [int]$ch
        if ($ch -eq '"') { [void]$sb.Append('\"') }
        elseif ($ch -eq '\') { [void]$sb.Append('\\') }
        elseif ($code -lt 32 -or $code -gt 126) { [void]$sb.Append('\u' + $code.ToString('x4')) }
        else { [void]$sb.Append($ch) }
    }
    [void]$sb.Append('"')
    return $sb.ToString()
}

function ConvertTo-JsonText {
    param($Value)

    if ($null -eq $Value) { return 'null' }

    # ConvertFrom-Json hands back PSCustomObjects. Unwrapping to .BaseObject is NOT enough: a bare
    # PSCustomObject matches none of the type tests below and would fall through to [string]$Value,
    # silently serializing as "". Walk its properties into a real JSON object instead.
    if ($null -ne $Value.PSObject -and
        $Value.PSObject.BaseObject -is [System.Management.Automation.PSCustomObject]) {
        $parts = @()
        foreach ($p in $Value.PSObject.Properties) {
            $parts += (ConvertTo-JsonStringLiteral ([string]$p.Name)) + ':' + (ConvertTo-JsonText $p.Value)
        }
        return '{' + ($parts -join ',') + '}'
    }
    if ($Value -is [System.Management.Automation.PSObject] -and $null -ne $Value.BaseObject) {
        $Value = $Value.BaseObject
    }

    if ($Value -is [bool]) { if ($Value) { return 'true' } else { return 'false' } }
    if ($Value -is [string]) { return (ConvertTo-JsonStringLiteral $Value) }

    if ($Value -is [byte] -or $Value -is [int16] -or $Value -is [uint16] -or
        $Value -is [int32] -or $Value -is [uint32] -or $Value -is [int64] -or $Value -is [uint64]) {
        return $Value.ToString([System.Globalization.CultureInfo]::InvariantCulture)
    }
    if ($Value -is [double] -or $Value -is [single] -or $Value -is [decimal]) {
        return $Value.ToString('R', [System.Globalization.CultureInfo]::InvariantCulture)
    }

    if ($Value -is [System.Collections.IDictionary]) {
        $parts = @()
        foreach ($k in $Value.Keys) {
            $parts += (ConvertTo-JsonStringLiteral ([string]$k)) + ':' + (ConvertTo-JsonText $Value[$k])
        }
        return '{' + ($parts -join ',') + '}'
    }

    # Must come AFTER the string test -- string is IEnumerable.
    if ($Value -is [System.Collections.IEnumerable]) {
        $parts = @()
        foreach ($item in $Value) { $parts += (ConvertTo-JsonText $item) }
        return '[' + ($parts -join ',') + ']'
    }

    return (ConvertTo-JsonStringLiteral ([string]$Value))
}

