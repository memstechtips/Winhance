#Requires -Version 5.1
<#
    Probe-WinhanceDefaults.ps1  --  Winhance fresh-install registry ground-truth probe

    WHAT THIS DOES
      Reads (never writes) every registry location the Winhance setting catalog detects from,
      and records for each one whether the value is PRESENT, ABSENT, or whether the parent KEY
      IS MISSING entirely. The point of the exercise is that "absent" is NOT the same as "off":
      Windows ships many settings with no registry value written at all, and only writes one
      once something explicitly sets it. This probe tells us which catalog targets are genuinely
      absent on a clean install so the catalog's WindowsDefault detection can be corrected.

    ############################################################################
    #  RUN THIS AS YOUR NORMAL USER.  DO NOT "RUN AS ADMINISTRATOR".           #
    #                                                                          #
    #  Most catalog targets live in HKEY_CURRENT_USER. An elevated shell reads #
    #  the ADMINISTRATOR account's HKCU, which is a different hive, and every   #
    #  per-user answer in the output would be silently wrong. The script       #
    #  refuses to run elevated for exactly this reason.                        #
    ############################################################################

    HOW TO RUN
      1. Copy this single file to the clean machine (Desktop is fine). Nothing to install.
      2. Open a NORMAL (non-elevated) PowerShell window.
      3. Run:
             powershell -ExecutionPolicy Bypass -File .\Probe-WinhanceDefaults.ps1
      4. Send back the .json file it writes next to itself. The path is printed at the end.

    STRICTLY READ-ONLY
      This script opens registry keys read-only and never writes, creates or deletes anything.
      powercfg targets are deliberately NOT probed, because unhiding a hidden powercfg setting
      requires WRITING Attributes = 0 to the registry, which would no longer be a clean-install
      reading. Those targets are recorded as "NotProbed".

    Generated by tests/Winhance.Infrastructure.Tests/Catalog/CatalogProbeManifestGeneratorTests.cs
    from extras/probe/Probe-WinhanceDefaults.template.ps1. Do not hand-edit the generated file;
    edit the template and regenerate.
#>

