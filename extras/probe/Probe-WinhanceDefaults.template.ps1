# =============================================================================================
# Registry reading
#
# THE ONE RULE THAT MATTERS: absent is tested with `$null -eq $value`, NEVER with truthiness.
# A DWORD of 0 and an empty REG_SZ are both FALSY in PowerShell, so `if (-not $value)` would
# report them as absent -- inverting the exact finding this probe exists to make.
# =============================================================================================

$baseKeyCache = @{}

function Get-BaseKey {
    param([string] $HiveToken)
    if ($baseKeyCache.ContainsKey($HiveToken)) { return $baseKeyCache[$HiveToken] }

    $hive = $null
    switch ($HiveToken) {
        'HKEY_CURRENT_USER'  { $hive = [Microsoft.Win32.RegistryHive]::CurrentUser }
        'HKCU'               { $hive = [Microsoft.Win32.RegistryHive]::CurrentUser }
        'HKEY_LOCAL_MACHINE' { $hive = [Microsoft.Win32.RegistryHive]::LocalMachine }
        'HKLM'               { $hive = [Microsoft.Win32.RegistryHive]::LocalMachine }
        'HKEY_CLASSES_ROOT'  { $hive = [Microsoft.Win32.RegistryHive]::ClassesRoot }
        'HKCR'               { $hive = [Microsoft.Win32.RegistryHive]::ClassesRoot }
        'HKEY_USERS'         { $hive = [Microsoft.Win32.RegistryHive]::Users }
        'HKU'                { $hive = [Microsoft.Win32.RegistryHive]::Users }
        'HKEY_CURRENT_CONFIG'{ $hive = [Microsoft.Win32.RegistryHive]::CurrentConfig }
        'HKCC'               { $hive = [Microsoft.Win32.RegistryHive]::CurrentConfig }
        default              { return $null }
    }

    # Registry64 explicitly: if this ever runs under 32-bit PowerShell, the default view would
    # silently redirect HKLM\SOFTWARE reads into WOW6432Node and produce wrong answers.
    $key = [Microsoft.Win32.RegistryKey]::OpenBaseKey($hive, [Microsoft.Win32.RegistryView]::Registry64)
    $baseKeyCache[$HiveToken] = $key
    return $key
}

function ConvertTo-RecordedValue {
    param($Raw)
    if ($null -eq $Raw) { return $null }
    if ($Raw -is [byte[]]) {
        $hex = New-Object System.Text.StringBuilder
        foreach ($b in $Raw) { [void]$hex.Append($b.ToString('X2')) }
        return [ordered]@{ '$bytes' = $hex.ToString(); length = $Raw.Length }
    }
    if ($Raw -is [string[]]) {
        $out = @()
        foreach ($s in $Raw) { $out += [string]$s }
        # Comma operator, deliberately: a bare `return $out` writes each element to the pipeline, so a
        # single-entry REG_MULTI_SZ would come back as a plain string and an EMPTY one as $null -- the
        # record would read status "Present" with a null value, which is precisely the
        # present-but-looks-absent ambiguity this whole probe exists to eliminate.
        return ,([string[]]$out)
    }
    if ($Raw -is [int32] -or $Raw -is [int64] -or $Raw -is [uint32] -or $Raw -is [uint64]) { return $Raw }
    return [string]$Raw
}

# Reads ONE path. Returns an ordered hashtable describing the tri-state.
#   status: 'KeyMissing' | 'ValueAbsent' | 'Present' | 'KeyPresent' | 'Error'
#   'KeyPresent' is for a ValueName-less target, whose state IS key existence.
function Read-OnePath {
    param([string] $Path, [string] $ValueName, [bool] $KeyExistenceOnly, [bool] $EnumerateSubKeys)

    $result = [ordered]@{
        path        = $Path
        status      = 'Error'
        value       = $null
        rawValue    = $null
        valueKind   = $null
        subKeys     = $null
        error       = $null
    }

    try {
        $sep = $Path.IndexOf('\')
        if ($sep -lt 1) { $result.error = 'Malformed path (no hive separator).'; return $result }
        $hiveToken = $Path.Substring(0, $sep).ToUpperInvariant()
        $subPath = $Path.Substring($sep + 1)

        $base = Get-BaseKey $hiveToken
        if ($null -eq $base) { $result.error = ('Unknown registry hive: {0}' -f $hiveToken); return $result }

        $key = $base.OpenSubKey($subPath, $false)
        if ($null -eq $key) { $result.status = 'KeyMissing'; return $result }

        try {
            if ($EnumerateSubKeys) {
                $names = @($key.GetSubKeyNames())
                $result.subKeys = $names
            }

            # A target whose ValueName is NULL encodes its state as key existence, not a stored value.
            #
            # This MUST NOT be an IsNullOrEmpty test. Four catalog targets declare ValueName as the EMPTY
            # STRING, which means the key's (Default) value and has to be read like any other value --
            # RegTargetReader branches on `is null`, not on emptiness. PowerShell cannot tell the two apart
            # once the value has been through a [string] cast, since [string]$null is "", so the manifest
            # carries the distinction as its own boolean and we trust that instead of re-deriving it.
            if ($KeyExistenceOnly) {
                $result.status = 'KeyPresent'
                return $result
            }

            $raw = $key.GetValue($ValueName, $null)

            # $null -eq, not truthiness. DWORD 0 and "" are falsy but PRESENT.
            if ($null -eq $raw) {
                $result.status = 'ValueAbsent'
                return $result
            }

            $result.status = 'Present'
            $result.value = ConvertTo-RecordedValue $raw
            try { $result.valueKind = [string]$key.GetValueKind($ValueName) } catch { }

            # REG_EXPAND_SZ: GetValue expands by default (mirroring what the app reads), but the
            # stored template is what actually distinguishes a Windows default from a user edit.
            if ($result.valueKind -eq 'ExpandString') {
                try {
                    $rawUnexpanded = $key.GetValue(
                        $ValueName, $null, [Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames)
                    $result.rawValue = ConvertTo-RecordedValue $rawUnexpanded
                } catch { }
            }
            return $result
        } finally {
            $key.Close()
        }
    } catch {
        $result.status = 'Error'
        $result.error = [string]$_.Exception.Message
        return $result
    }
}

# Mirrors Winhance.Core RegTargetReader.OrderHklmFirst: mirror paths fold HKLM-first, and the
# first non-null read wins. Per-path detail is kept regardless -- knowing that Windows writes
# one mirror and not the other is a large part of what we are trying to learn here.
function Get-HklmFirstOrder {
    param([string[]] $Paths)
    $hklm = @()
    $rest = @()
    foreach ($p in $Paths) {
        if ($p.ToUpperInvariant().StartsWith('HKEY_LOCAL_MACHINE')) { $hklm += $p } else { $rest += $p }
    }
    return @($hklm + $rest)
}

