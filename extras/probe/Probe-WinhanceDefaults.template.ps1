$taskResults = @()
foreach ($setting in $settings) {
    foreach ($target in @($setting.targets)) {
        if ($target.kind -ne 'Task') { continue }
        $entry = [ordered]@{
            settingId = [string]$setting.id
            key       = [string]$target.key
            taskPath  = [string]$target.taskPath
            state     = $null
            enabled   = $null
            error     = $null
        }
        try {
            $leaf = Split-Path -Leaf ([string]$target.taskPath)
            $folder = Split-Path -Parent ([string]$target.taskPath)
            if ([string]::IsNullOrEmpty($folder)) { $folder = '\' }
            # Get-ScheduledTask -TaskPath wants a leading AND trailing backslash; a manifest path
            # authored without the leading one would silently match nothing.
            if (-not $folder.StartsWith('\')) { $folder = '\' + $folder }
            if (-not $folder.EndsWith('\')) { $folder = $folder + '\' }
            $task = Get-ScheduledTask -TaskName $leaf -TaskPath $folder -ErrorAction Stop
            $entry.state = [string]$task.State
            $entry.enabled = ($task.State -ne 'Disabled')
        } catch {
            $entry.error = [string]$_.Exception.Message
        }
        $taskResults += $entry
    }
}

# =============================================================================================
# PowerCfg DEFAULTS -- read-only. The DEFAULT AC/DC index for each built-in power setting is static
# data in the SYSTEM hive under
#   HKLM\SYSTEM\CurrentControlSet\Control\Power\PowerSettings\<subgroup>\<setting>\DefaultPowerSchemeValues\<scheme>
# with ACSettingIndex / DCSettingIndex per scheme. This is the true shipped default WITHOUT the write
# that unhiding a hidden setting would need, so v1's powercfg-skip does not apply to reading defaults.
# Control\Power is readable by a standard user, so no elevation.
# =============================================================================================

function Read-PowerCfgDefaults {
    param([string] $Subgroup, [string] $Setting)

    $result = [ordered]@{ status = 'KeyMissing'; schemes = @(); error = $null }
    try {
        $base = Get-BaseKey 'HKEY_LOCAL_MACHINE'
        if ($null -eq $base) { $result.error = 'no HKLM base key'; $result.status = 'Error'; return $result }

        $sub = $Subgroup.Trim('{', '}')
        $set = $Setting.Trim('{', '}')
        $path = "SYSTEM\CurrentControlSet\Control\Power\PowerSettings\$sub\$set\DefaultPowerSchemeValues"
        $key = $base.OpenSubKey($path, $false)
        if ($null -eq $key) { return $result }  # KeyMissing -- setting not present on this machine

        try {
            $schemeEntries = @()
            foreach ($schemeName in @($key.GetSubKeyNames())) {
                $sk = $key.OpenSubKey($schemeName, $false)
                if ($null -eq $sk) { continue }
                try {
                    # $null -eq means absent, not 0. A REG_DWORD arrives as Int32, so [int] never overflows;
                    # the "never" sentinel 0xFFFFFFFF reads as -1 here, which is exactly how Winhance reads it.
                    $ac = $sk.GetValue('ACSettingIndex', $null)
                    $dc = $sk.GetValue('DCSettingIndex', $null)
                    $schemeEntries += [ordered]@{
                        scheme = [string]$schemeName
                        ac     = $(if ($null -eq $ac) { $null } else { [int]$ac })
                        dc     = $(if ($null -eq $dc) { $null } else { [int]$dc })
                    }
                } finally { $sk.Close() }
            }
            $result.schemes = $schemeEntries
            $result.status = if ($schemeEntries.Count -gt 0) { 'Present' } else { 'NoSchemes' }
        } finally { $key.Close() }
    } catch {
        $result.status = 'Error'
        $result.error = [string]$_.Exception.Message
    }
    return $result
}

$powerCfgDefaults = @()
foreach ($setting in $settings) {
    foreach ($target in @($setting.targets)) {
        if ($target.kind -ne 'PowerCfg') { continue }
        $d = Read-PowerCfgDefaults ([string]$target.subgroupGuid) ([string]$target.settingGuid)
        $powerCfgDefaults += [ordered]@{
            settingId    = [string]$setting.id
            key          = [string]$target.key
            subgroupGuid = [string]$target.subgroupGuid
            settingGuid  = [string]$target.settingGuid
            mode         = [string]$target.mode
            units        = [string]$target.units
            status       = [string]$d.status
            schemes      = $d.schemes
            error        = $d.error
        }
    }
}

# =============================================================================================
# Headline finding: which settings' WindowsDefault state reads ABSENT here while that state's
# StateValue does NOT accept absence. Those are the ones whose detection cannot be right on a
# clean install. No value comparison is involved -- this is purely presence -- so it cannot be
# wrong for the subtle reasons a naive re-implementation of the matcher would be.
# =============================================================================================

function Test-BuildInRanges {
    param($Ranges, [int] $Build, [int] $Revision)
    $list = @($Ranges)
    if ($list.Count -eq 0) { return $true }   # unconditional
    foreach ($r in $list) {
        $minB = [int]$r.minBuild; $minR = [int]$r.minRevision
        $maxB = [int]$r.maxBuild; $maxR = [int]$r.maxRevision
        $geMin = ($Build -gt $minB) -or (($Build -eq $minB) -and ($Revision -ge $minR))
        $leMax = ($Build -lt $maxB) -or (($Build -eq $maxB) -and ($Revision -le $maxR))
        if ($geMin -and $leMax) { return $true }
    }
    return $false
}

# Keyed by joinKey, not key: four targets have an empty Key, and an empty-string hashtable/property name is
# not something to rely on round-tripping through ConvertFrom-Json.
$statusBySettingTarget = @{}
foreach ($r in $results) {
    foreach ($t in $r.targets) { $statusBySettingTarget[($r.id + '|' + $t.joinKey)] = $t.status }
}

# Target metadata, needed to keep several classes of false positive OUT OF THE COUNT. Note they are recorded
# and flagged rather than skipped -- a silently dropped suspect is indistinguishable from a clean result.
$targetMetaBySettingTarget = @{}
foreach ($setting in $settings) {
    foreach ($target in @($setting.targets)) {
        $targetMetaBySettingTarget[([string]$setting.id + '|' + [string]$target.joinKey)] = $target
    }
}

$suspects = @()
foreach ($setting in $settings) {
    $hasFallback = $false
    foreach ($st in @($setting.states)) { if ([bool]$st.isFallback) { $hasFallback = $true } }

    foreach ($st in @($setting.states)) {
        # Roles are per power CONTEXT (Always / AC / DC) as well as per build, so collect the contexts
        # in which this state is the Windows default here rather than reducing to one boolean.
        $wdContexts = @()
        foreach ($role in @($st.roles)) {
            if ([string]$role.kind -ne 'WindowsDefault') { continue }
            # A build-SCOPED role (non-empty appliesTo) is the OS-divergent default -- e.g. the This PC
            # folder settings default Enabled on Windows 10 and Disabled on Windows 11. It must be
            # judged against THIS machine's build or the wrong state is treated as the default.
            if (Test-BuildInRanges $role.appliesTo $machine.buildNumber $machine.ubr) {
                $wdContexts += [string]$role.context
            }
        }
        if ($wdContexts.Count -eq 0) { continue }

        foreach ($prop in @($st.set.PSObject.Properties)) {
            $targetKey = [string]$prop.Name
            $sv = $prop.Value
            if ([bool]$sv.acceptsAbsent) { continue }      # already handles absence correctly
            if ([bool]$sv.acceptsAnyPresent) { continue }

            $lookup = [string]$setting.id + '|' + $targetKey
            $meta = $targetMetaBySettingTarget[$lookup]

            if ($null -eq $meta) {
                # A Set entry naming a target the setting does not declare. Recorded rather than
                # skipped -- silently dropping it would quietly shrink the finding.
                $suspects += [ordered]@{
                    id = [string]$setting.id; control = [string]$setting.control
                    stateLabel = [string]$st.label; contexts = $wdContexts
                    targetKey = $targetKey; targetKind = 'Unknown'; status = 'NoSuchTarget'
                    hasFallback = $hasFallback; hasDetector = ($null -ne $setting.detector)
                    applyOnly = $false; targetAppliesHere = $false; settingAppliesHere = $false
                    perSubKeyTarget = $false; countsTowardFinding = $false
                }
                continue
            }

            $status = $statusBySettingTarget[$lookup]
            if ($status -ne 'ValueAbsent' -and $status -ne 'KeyMissing') { continue }

            # Gates that disqualify a reading from being EVIDENCE of a detection bug. Each is recorded
            # rather than used to skip, so the JSON stays complete and only the headline count narrows.
            #   applyOnly    - excluded from the precedence path's deciding-target selection, so an absent
            #                  reading there proves nothing (it can still matter on a whole-pattern setting).
            #   target build - a target scoped to other builds is not live here and reads absent everywhere.
            #   setting build- likewise for the setting's own availability.
            #   perSubKey    - PerNetworkInterface / PerMonitor mean "all subkeys must match", which
            #                  RegTargetReader does not implement; the parent read is not the real answer.
            $targetLive = Test-BuildInRanges $meta.appliesTo $machine.buildNumber $machine.ubr
            $settingLive = Test-BuildInRanges $setting.availability.builds $machine.buildNumber $machine.ubr
            $perSubKey = ([bool]$meta.perNetworkInterface) -or ([bool]$meta.perMonitor)

            $suspects += [ordered]@{
                id             = [string]$setting.id
                control        = [string]$setting.control
                stateLabel     = [string]$st.label
                contexts       = $wdContexts
                targetKey      = $targetKey
                targetKind     = [string]$meta.kind
                status         = [string]$status
                hasFallback    = $hasFallback
                hasDetector    = ($null -ne $setting.detector)
                applyOnly      = [bool]$meta.applyOnly
                targetAppliesHere  = $targetLive
                settingAppliesHere = $settingLive
                perSubKeyTarget    = $perSubKey
                countsTowardFinding = ((-not [bool]$meta.applyOnly) -and $targetLive -and $settingLive -and (-not $perSubKey))
            }
        }
    }
}

# =============================================================================================
# Write the output file
# =============================================================================================

$document = [ordered]@{
    probeSchemaVersion = $ProbeSchemaVersion
    manifestSchema     = $manifest.schemaVersion
    catalogHash        = [string]$manifest.catalogHash   # ties this result to the exact catalog revision it was run against
    machine            = $machine
    counts             = $counts
    settings           = $results
    scheduledTasks     = $taskResults
    powerCfgDefaults   = $powerCfgDefaults
    absentWindowsDefaultSuspects = $suspects
}

$editionTag = [string]$machine.editionId
if ([string]::IsNullOrEmpty($editionTag)) { $editionTag = 'UnknownEdition' }
$fileName = ('winhance-defaults-probe_{0}.{1}_{2}_{3}_{4}.json' -f `
    $machine.buildNumber, $machine.ubr, $editionTag, $machine.computerName,
    (Get-Date).ToString('yyyyMMdd-HHmmss'))

$candidateDirs = @()
if (-not [string]::IsNullOrEmpty($OutputDir)) { $candidateDirs += $OutputDir }
if (-not [string]::IsNullOrEmpty($PSScriptRoot)) { $candidateDirs += $PSScriptRoot }
$candidateDirs += [System.Environment]::GetFolderPath('Desktop')
$candidateDirs += [string]$env:TEMP

$json = ConvertTo-JsonText $document
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

$outPath = $null
$writeFailures = @()
foreach ($dir in $candidateDirs) {
    if ([string]::IsNullOrEmpty($dir)) { continue }
    try {
        if (-not (Test-Path -LiteralPath $dir)) { continue }
        # Resolve-Path first: Test-Path and Join-Path resolve against PowerShell's location, but
        # [System.IO.File] resolves against the .NET process working directory, and the two routinely
        # differ. A relative -OutputDir would otherwise write the file somewhere other than reported.
        $fullDir = (Resolve-Path -LiteralPath $dir).ProviderPath
        $attempt = [System.IO.Path]::GetFullPath((Join-Path $fullDir $fileName))
        [System.IO.File]::WriteAllText($attempt, $json, $utf8NoBom)
        $outPath = $attempt
        break
    } catch {
        $writeFailures += ('{0}: {1}' -f $dir, $_.Exception.Message)
    }
}

if ($null -eq $outPath) {
    Write-Host ''
    Write-Host '  FAILED to write the output file to any candidate location.' -ForegroundColor Red
    foreach ($f in $writeFailures) { Write-Host ('    {0}' -f $f) -ForegroundColor Red }
    Write-Host ('  Tried: {0}' -f ($candidateDirs -join '; ')) -ForegroundColor Red
    exit 4
}

